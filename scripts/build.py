"""Generate the two standalone Open WebUI Functions in dist/."""

import ast
import base64
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "openwebui_chatgpt_connect"
DIST = ROOT / "dist"
ADMIN_PAGE_LOADER = (
    'ADMIN_HTML = (Path(__file__).parent / "assets" / "admin.html").read_text(encoding="utf-8")'
)
MODEL_AVATAR_LOADER = """MODEL_AVATAR = base64.b64encode(
    (Path(__file__).parent / "assets" / "chatgpt.png").read_bytes()
).decode()"""


def embed_assets(source: str) -> str:
    if source.count(ADMIN_PAGE_LOADER) != 1 or source.count(MODEL_AVATAR_LOADER) != 1:
        raise ValueError("admin.py must contain the canonical HTML and avatar loaders")
    html = (SOURCE / "assets" / "admin.html").read_text(encoding="utf-8")
    if '"""' in html:
        raise ValueError("admin.html cannot contain a triple-double-quote")
    avatar = base64.b64encode((SOURCE / "assets" / "chatgpt.png").read_bytes()).decode()
    return source.replace(ADMIN_PAGE_LOADER, f'ADMIN_HTML = r"""{html}"""').replace(
        MODEL_AVATAR_LOADER, f'MODEL_AVATAR = "{avatar}"'
    )


def bundle(modules: tuple[str, ...]) -> str:
    imports = set()
    bodies = []
    for name in modules:
        path = SOURCE / f"{name}.py"
        source = path.read_text(encoding="utf-8")
        if name == "admin":
            source = embed_assets(source)
        omitted = set()
        for index, node in enumerate(ast.parse(source).body):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                if not (isinstance(node, ast.ImportFrom) and node.level):
                    imports.add(ast.unparse(node))
            elif (
                index == 0
                and isinstance(node, ast.Expr)
                and isinstance(node.value, ast.Constant)
                and isinstance(node.value.value, str)
            ):
                pass
            else:
                continue
            omitted.update(range(node.lineno, node.end_lineno + 1))
        body = "\n".join(
            line for number, line in enumerate(source.splitlines(), 1) if number not in omitted
        ).strip()
        bodies.append(f"# --- {path.relative_to(ROOT).as_posix()} ---\n\n{body}")
    return "\n".join(sorted(imports)) + "\n\n\n" + "\n\n\n".join(bodies) + "\n"


def artifacts() -> dict[str, str]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    metadata = project["project"]
    function = project["tool"]["openwebui-chatgpt-connect"]

    def render(modules, title, description, requirements):
        header = "\n".join(
            [
                '"""',
                f"title: {title}",
                f"author: {metadata['authors'][0]['name']}",
                f"description: {description}",
                f"version: {metadata['version']}",
                f"license: {metadata['license']}",
                f"required_open_webui_version: {function['required-open-webui-version']}",
                *([f"requirements: {','.join(requirements)}"] if requirements else []),
                '"""',
                "",
                "# Generated by: uv run python scripts/build.py - edit src/, not this file.",
            ]
        )
        return header + "\n\n" + bundle(modules)

    generated = {
        "openwebui_chatgpt_connect.py": render(
            ("file_inputs", "settings", "auth", "responses", "admin", "function"),
            function["title"],
            metadata["description"],
            metadata["dependencies"],
        ),
        "chatgpt_responses_history.py": render(
            ("file_inputs", "history_filter"),
            "ChatGPT Responses History",
            "Preserve ChatGPT reasoning and send original uploaded documents through Responses.",
            [],
        ),
    }
    for name, source in generated.items():
        compile(source, name, "exec")
    return generated


if __name__ == "__main__":
    DIST.mkdir(parents=True, exist_ok=True)
    for name, content in artifacts().items():
        output = DIST / name
        output.write_text(content, encoding="utf-8")
        print(f"Built {output}")
