"""Bundle the source dependency graph into one importable Open WebUI Function."""

import argparse
import ast
import base64
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "openwebui_chatgpt_connect"
OUTPUT = ROOT / "dist" / "openwebui_chatgpt_connect.py"
ADMIN_PAGE = SOURCE / "assets" / "admin.html"
MODEL_AVATAR = SOURCE / "assets" / "chatgpt.png"
ADMIN_PAGE_LOADER = (
    'ADMIN_HTML = (Path(__file__).parent / "assets" / "admin.html").read_text(encoding="utf-8")'
)
MODEL_AVATAR_LOADER = """MODEL_AVATAR = base64.b64encode(
    (Path(__file__).parent / "assets" / "chatgpt.png").read_bytes()
).decode()"""


def embed_assets(source: str) -> str:
    if source.count(ADMIN_PAGE_LOADER) != 1:
        raise ValueError("admin.py must contain exactly one canonical HTML loader")
    if source.count(MODEL_AVATAR_LOADER) != 1:
        raise ValueError("admin.py must contain exactly one canonical avatar loader")
    html = ADMIN_PAGE.read_text(encoding="utf-8")
    if '"""' in html:
        raise ValueError("admin.html cannot contain a triple-double-quote")
    avatar = base64.b64encode(MODEL_AVATAR.read_bytes()).decode()
    return source.replace(ADMIN_PAGE_LOADER, f'ADMIN_HTML = r"""{html}"""').replace(
        MODEL_AVATAR_LOADER, f'MODEL_AVATAR = "{avatar}"'
    )


def render() -> str:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    metadata = project["project"]
    function = project["tool"]["openwebui-chatgpt-connect"]
    header = "\n".join(
        [
            '"""',
            f"title: {function['title']}",
            f"author: {metadata['authors'][0]['name']}",
            f"description: {metadata['description']}",
            f"version: {metadata['version']}",
            f"required_open_webui_version: {function['required-open-webui-version']}",
            f"requirements: {','.join(metadata['dependencies'])}",
            '"""',
            "",
            "# Generated by: uv run python scripts/build.py - edit src/, not this file.",
        ]
    )
    imports: set[str] = set()
    bodies: list[str] = []
    visited: set[str] = set()
    visiting: set[str] = set()

    def visit(name: str):
        if name in visited:
            return
        if name in visiting:
            raise ValueError(f"Circular source dependency: {name}")
        visiting.add(name)
        path = SOURCE / f"{name}.py"
        source = path.read_text(encoding="utf-8")
        if name == "admin":
            source = embed_assets(source)
        tree = ast.parse(source, filename=str(path))
        omitted: set[int] = set()
        for index, node in enumerate(tree.body):
            if isinstance(node, ast.ImportFrom) and node.level:
                if (
                    node.level != 1
                    or not node.module
                    or "." in node.module
                    or any(item.asname or item.name == "*" for item in node.names)
                ):
                    raise ValueError(f"Unsupported local import in {path.name}:{node.lineno}")
                visit(node.module)
            elif isinstance(node, (ast.Import, ast.ImportFrom)):
                if isinstance(node, ast.ImportFrom) and node.module == "__future__":
                    raise ValueError("Future imports need explicit bundler support")
                imports.add(ast.unparse(node))
            elif (
                index == 0
                and isinstance(node, ast.Expr)
                and isinstance(node.value, ast.Constant)
                and isinstance(node.value.value, str)
            ):
                pass
            else:
                continue
            omitted.update(range(node.lineno, node.end_lineno + 1))
        body = "\n".join(
            line for number, line in enumerate(source.splitlines(), 1) if number not in omitted
        ).strip()
        bodies.append(f"# --- {path.relative_to(ROOT).as_posix()} ---\n\n{body}")
        visiting.remove(name)
        visited.add(name)

    visit("function")
    result = header + "\n\n" + "\n".join(sorted(imports)) + "\n\n\n" + "\n\n\n".join(bodies) + "\n"
    compile(result, str(OUTPUT), "exec")
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the artifact is missing or stale"
    )
    args = parser.parse_args()
    content = render()
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
            print(f"Missing or stale artifact: {args.output}; run uv run python scripts/build.py")
            return 1
        print(f"Artifact is up to date: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"Built {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
